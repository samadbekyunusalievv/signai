/* Build signai.html: one self-contained file with all CSS and JS inlined.
   It can be double-clicked, emailed or copied anywhere — no server, no folders.
   Usage: node tools/build-single.js   (also run by `npm run build`) */
"use strict";
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const read = p => fs.readFileSync(path.join(ROOT, p), "utf8");
// keep "</script>" inside inlined code from closing the tag early
const safe = js => js.replace(/<\/script/gi, "<\\/script");

let html = read("index.html");

html = html.replace(/<link rel="stylesheet" href="([^"]+)"\s*\/?>/g, (_, href) => `<style>\n${read(href)}\n</style>`);
html = html.replace(/<script src="(js\/[^"]+)"><\/script>/g, (_, src) => `<script>\n/* ---- ${src} ---- */\n${safe(read(src))}\n</script>`);
html = html.replace("<head>", "<head>\n<!-- GENERATED by tools/build-single.js from index.html + css/ + js/. Edit those, then run `npm run build`. -->");

const left = html.match(/(?:src|href)="(?:css|js)\/[^"]+"/g);
if (left) throw new Error("Not inlined: " + left.join(", "));

fs.writeFileSync(path.join(ROOT, "signai.html"), html);
console.log(`signai.html written (${(html.length / 1024).toFixed(0)} KB)`);
